--
-- Spec 02: refresh tokens are durable credentials for the HttpOnly cookie
-- session. Only the SHA-256 of each token is stored, never the token itself,
-- so a data leak cannot replay a cookie. family_id groups the rotation chain
-- of one login: presenting a revoked (rotated-away) token revokes the whole
-- family of that row.
--
CREATE TABLE refresh_tokens (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT NOT NULL,
    family_id   VARCHAR(36) NOT NULL,
    token_hash  VARCHAR(64) NOT NULL,
    expires_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    revoked_at  TIMESTAMP WITH TIME ZONE NULL,
    replaced_by BIGINT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_refresh_tokens_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT uq_refresh_tokens_token_hash UNIQUE (token_hash)
);

CREATE INDEX idx_refresh_tokens_family_id ON refresh_tokens (family_id);
