--
-- Knowledge memory (spec 03): past proposal PDFs are split into passages and
-- priced line items, embedded, and stored per agency. The portable tables hold
-- the documents and chunks for every database; embeddings live in
-- knowledge_vectors as raw little-endian float bytes so the same DDL also
-- migrates H2. The pgvector-accelerated copy is created only by the
-- PostgreSQL vendor migration V24, and both vector tables share the columns
-- the kernel metadata needs (agency, document, kind, requirement type).
--
CREATE TABLE knowledge_documents (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agency_id          BIGINT NOT NULL,
    name               TEXT NOT NULL,          -- encrypted
    kind               VARCHAR(30) NOT NULL,
    source_proposal_id BIGINT,
    page_count         INT,
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_knowledge_documents_agency FOREIGN KEY (agency_id)
        REFERENCES agencies (id) ON DELETE CASCADE,
    CONSTRAINT ck_knowledge_documents_kind CHECK (kind IN ('PROPOSAL_PDF', 'APPROVED_PROPOSAL'))
);

CREATE TABLE knowledge_chunks (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id      BIGINT NOT NULL,
    kind             VARCHAR(20) NOT NULL,
    text             TEXT NOT NULL,          -- encrypted
    page             INT,                    -- passage origin page; line items sit on page 1
    requirement_type VARCHAR(255),           -- catalog name, plaintext; NULL for passages
    hours            NUMERIC(10, 2),         -- approved hours for line items; NULL for passages
    ordinal          INT NOT NULL,
    CONSTRAINT fk_knowledge_chunks_document FOREIGN KEY (document_id)
        REFERENCES knowledge_documents (id) ON DELETE CASCADE,
    CONSTRAINT ck_knowledge_chunks_kind CHECK (kind IN ('PASSAGE', 'ITEM')),
    CONSTRAINT ck_knowledge_chunks_hours CHECK (hours IS NULL OR hours >= 0)
);

CREATE INDEX idx_knowledge_chunks_document ON knowledge_chunks (document_id);

-- Vector index for the portable (exact cosine in Java) store. One row per
-- embedded chunk, replaced by chunk_id on re-embed. dims recorded so mixed
-- embedding models (stub 256 / Voyage 1024) can be detected.
CREATE TABLE knowledge_vectors (
    chunk_id         BIGINT PRIMARY KEY,
    agency_id        BIGINT NOT NULL,
    document_id      BIGINT NOT NULL,
    kind             VARCHAR(20) NOT NULL,
    requirement_type VARCHAR(255),
    dims             INT NOT NULL,
    vector           BYTEA NOT NULL,
    CONSTRAINT fk_knowledge_vectors_chunk FOREIGN KEY (chunk_id)
        REFERENCES knowledge_chunks (id) ON DELETE CASCADE
);

CREATE INDEX idx_knowledge_vectors_agency_kind ON knowledge_vectors (agency_id, kind);
