--
-- WhatsApp: a verified number per user, and the outbox the WhatsApp service sends from.
--
-- Portable on purpose (no vendor syntax), like V30, so it lives in db/migration.
--
-- whatsapp_contacts holds only numbers their owner proved they hold with a code sent to them: a typo must not
-- send an agency's quotation notices to a stranger. One number per user (user_id is the key).
--
-- whatsapp_messages is an outbox. The backend never calls WhatsApp: it writes a row in the same transaction as the
-- event (a proposal changing state, a code being requested), and the separate WhatsApp service claims rows over
-- HTTP and reports the outcome. A row survives the service being off until expires_at. claimed_at is a lease: a row
-- claimed but not reported within a minute is offered again, at most three times (attempts).
--
-- phone and body are encrypted at rest like the rest of the agency data (V21), hence TEXT. A finished row keeps its
-- status and error as evidence but its body is cleared, since it may hold a verification code.
--
CREATE TABLE whatsapp_contacts (
    user_id      BIGINT PRIMARY KEY,
    phone        TEXT NOT NULL,
    enabled      BOOLEAN NOT NULL,
    verified_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_whatsapp_contacts_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE TABLE whatsapp_messages (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    phone        TEXT NOT NULL,
    body         TEXT NOT NULL,
    status       VARCHAR(20) NOT NULL,
    attempts     INTEGER NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    claimed_at   TIMESTAMP WITH TIME ZONE NULL,
    finished_at  TIMESTAMP WITH TIME ZONE NULL,
    error        VARCHAR(200) NULL,
    CONSTRAINT ck_whatsapp_messages_status CHECK (status IN ('PENDING', 'SENT', 'FAILED'))
);

CREATE INDEX idx_whatsapp_messages_status_id ON whatsapp_messages (status, id);
