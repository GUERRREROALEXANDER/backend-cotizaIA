--
-- Spec 16: email verification of new accounts.
--
-- Portable on purpose (BOOLEAN + TIMESTAMP WITH TIME ZONE, no vendor syntax), so it lives in
-- db/migration next to V28 and V29 instead of the vendor folders, which are reserved for
-- statements such as V24's CREATE EXTENSION vector.
--
-- users.email_verified defaults to TRUE: every account created before this migration keeps
-- working (its owner already received and can use the product), and only a register call made
-- while MAIL_VERIFICATION_REQUIRED=true creates a row with FALSE.
--
-- email_verification_tokens stores only the SHA-256 of the mailed token, never the token itself,
-- so a database leak cannot be replayed as a link. used_at makes a token single use; expires_at
-- (24 h) makes it short lived. A used or expired row stays as evidence.
--
ALTER TABLE users ADD COLUMN email_verified BOOLEAN NOT NULL DEFAULT TRUE;

CREATE TABLE email_verification_tokens (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT NOT NULL,
    token_hash  VARCHAR(64) NOT NULL,
    expires_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    used_at     TIMESTAMP WITH TIME ZONE NULL,
    CONSTRAINT fk_email_verification_tokens_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT uq_email_verification_tokens_token_hash UNIQUE (token_hash)
);

CREATE INDEX idx_email_verification_tokens_user_id ON email_verification_tokens (user_id);
