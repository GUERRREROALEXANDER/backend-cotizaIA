--
-- Spec 06: negotiation revisions (Prototype) and undoable hour edits (Command).
--
-- revision_number counts the versions of an offer. revision_of_id links a
-- revision to the frozen proposal it was copied from; the original is kept
-- (and moved to EXPIRED) so the client's version stays auditable.
--
-- proposal_commands is the append-only command log behind the approval queue:
-- every hour edit is a row that can be undone step by step. payload and
-- description are encrypted at rest (they may carry client requirement text),
-- so their columns are TEXT and the domain converter owns the encryption.
--
ALTER TABLE proposals ADD COLUMN revision_number INT NOT NULL DEFAULT 1;
ALTER TABLE proposals ADD COLUMN revision_of_id BIGINT NULL;
ALTER TABLE proposals ADD CONSTRAINT fk_proposals_revision_of
    FOREIGN KEY (revision_of_id) REFERENCES proposals (id);

CREATE TABLE proposal_commands (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proposal_id  BIGINT NOT NULL,
    command_type VARCHAR(40) NOT NULL,
    payload      TEXT NOT NULL,
    description  TEXT NOT NULL,
    executed_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    undone_at    TIMESTAMP WITH TIME ZONE NULL,
    CONSTRAINT fk_proposal_commands_proposal FOREIGN KEY (proposal_id)
        REFERENCES proposals (id) ON DELETE CASCADE
);

CREATE INDEX idx_proposal_commands_proposal_id ON proposal_commands (proposal_id);
CREATE INDEX idx_proposals_revision_of_id ON proposals (revision_of_id);
