--
-- PDF brief uploads keep the original RFP beside the brief they produced.
-- The channel set gains PDF, and one attachment row per brief retains the
-- uploaded bytes so the operator can always download exactly what arrived.
--
ALTER TABLE briefs DROP CONSTRAINT ck_briefs_source;
ALTER TABLE briefs ADD CONSTRAINT ck_briefs_source CHECK (source IN ('EMAIL', 'WHATSAPP', 'WEB_FORM', 'PDF'));

CREATE TABLE brief_attachments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    brief_id BIGINT NOT NULL UNIQUE,
    file_name VARCHAR(255) NOT NULL,
    content_type VARCHAR(60) NOT NULL,
    size_bytes BIGINT NOT NULL,
    page_count INT NOT NULL,
    content BYTEA NOT NULL,
    uploaded_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_brief_attachments_brief FOREIGN KEY (brief_id) REFERENCES briefs(id) ON DELETE CASCADE,
    CONSTRAINT ck_brief_attachments_size CHECK (size_bytes > 0)
);
